"""Native PGFPlots fragments for the three manuscript panels."""

from pathlib import Path

import numpy as np


class PaperFigures:
    """Keep the original palette, line styles, axes, SEM and panel proportions.

    Fragments inherit the enclosing manuscript's font; input them directly
    inside the existing minipages, without scaling an embedded PDF.
    """

    def plot(self, summaries, figure, output_dir):
        output = Path(output_dir)
        files = []
        for group, filename in (
            ("comparison", "cumulative_regret"),
            ("feedback", "final_regret_vs_m"),
            ("mnl", "final_regret_vs_theta0"),
        ):
            selected = [s for s in summaries if s.labels["group"] == group]
            if not selected:
                continue
            lines = [
                "% Generated by EWS from independent runs; bands/bars are mean +/- SEM.",
                r"\begin{tikzpicture}",
                r"\definecolor{paperblue}{HTML}{1F77B4}",
                r"\definecolor{paperorange}{HTML}{FF7F0E}",
                r"\definecolor{papergreen}{HTML}{2CA02C}",
            ]
            options = [
                r"width=\linewidth",
                r"height=0.91\linewidth",
                r"font=\scriptsize",
                "grid=major",
                "grid style={gray!30}",
                "tick align=outside",
                r"ylabel={Cumulative Top-$k$ Regret}",
                r"legend style={font=\tiny,draw=gray!30,fill=white,cells={anchor=west}}",
            ]
            if group == "comparison":
                options += [
                    "xlabel={Learning Horizon}",
                    "xmin=0",
                    "ymin=0",
                    "scaled x ticks=base 10:-6",
                    "legend pos=south west",
                ]
                series = [
                    (s.labels["algorithm.name"], s.x, s.mean, s.uncertainty)
                    for s in selected
                ]
            else:
                key = "data.params.m" if group == "feedback" else "data.params.theta0"
                options += (
                    [r"xlabel={Feedback Level $m$}", "xtick={1,2,3,6}", "ymin=0"]
                    if group == "feedback"
                    else [
                        r"xlabel={``No-Choice'' Parameter $\theta_0$}",
                        "xmode=log",
                        "ymode=log",
                        "legend pos=north east",
                    ]
                )
                series = []
                for name in sorted({s.labels["algorithm.name"] for s in selected}):
                    rows = sorted(
                        [s for s in selected if s.labels["algorithm.name"] == name],
                        key=lambda s: s.labels[key],
                    )
                    series.append(
                        (
                            name,
                            np.array([s.labels[key] for s in rows]),
                            np.array([s.mean[-1] for s in rows]),
                            np.array([s.uncertainty[-1] for s in rows]),
                        )
                    )
            lines.append(r"\begin{axis}[" + ",\n".join(options) + "]")
            styles = {
                "topk_uif": ("paperblue,solid", r"\textsc{Top-$k$-UIF}"),
                "rec_maxmin_ucb": ("paperorange,dashed", r"\textsc{RecMaxMinUCB}"),
                "mnl_topk_uif": ("paperblue,solid", r"\textsc{MNL-Top-$k$-UIF}"),
                "sg_adaptive": (
                    "paperorange,dashdotted",
                    r"\textsc{AOA-RB}$_{\mathrm{PL}}$-\textsc{Adaptive}",
                ),
                "sg_no_choice": (
                    "papergreen,dashed",
                    r"\textsc{AOA-RB}$_{\mathrm{PL}}$",
                ),
            }
            # Match the manuscript's legend ordering.
            series.sort(key=lambda row: list(styles).index(row[0]))
            for index, (name, x, mean, sem) in enumerate(series):
                style, label = styles[name]
                if group == "comparison":
                    if np.isfinite(sem).all():
                        for suffix, values in (("lo", mean - sem), ("hi", mean + sem)):
                            coords = " ".join(
                                f"({a:.12g},{b:.12g})" for a, b in zip(x, values)
                            )
                            lines.append(
                                rf"\addplot[draw=none,name path=c{index}{suffix},forget plot] coordinates {{{coords}}};"
                            )
                        color = style.split(",")[0]
                        lines.append(
                            rf"\addplot[{color},fill opacity=0.18,draw=none,forget plot] fill between[of=c{index}lo and c{index}hi];"
                        )
                    coords = " ".join(f"({a:.12g},{b:.12g})" for a, b in zip(x, mean))
                    lines.append(rf"\addplot[{style},thick] coordinates {{{coords}}};")
                else:
                    coords = " ".join(
                        f"({a:.12g},{b:.12g}) +- (0,{e:.12g})"
                        for a, b, e in zip(x, mean, np.nan_to_num(sem))
                    )
                    lines.append(
                        rf"\addplot[{style},thick,mark=*,mark size=1.4pt,error bars/.cd,y dir=both,y explicit] coordinates {{{coords}}};"
                    )
                if group != "feedback":
                    lines.append(r"\addlegendentry{" + label + "}")
            lines += [r"\end{axis}", r"\end{tikzpicture}", ""]
            path = output / (filename + ".tikz")
            path.write_text("\n".join(lines))
            files.append(path)
        return files
